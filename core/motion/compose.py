def _clean(value: Any) -> str:
    return " ".join(str(value if value is not None else "").split())


def fit(value: Any, chars: int, lines: int = 1) -> str:
    """`value` wrapped to at most `lines` lines of at most `chars`
    characters, trimmed with an ellipsis when it does not fit. Text that
    already carries newlines and fits is kept as written."""
    raw = str(value if value is not None else "")
    if "\n" in raw:
        rows = [r.strip() for r in raw.split("\n") if r.strip()]
        if len(rows) <= lines and all(len(r) <= chars for r in rows):
            return "\n".join(rows)
    text = _clean(raw)
    if not text:
        return ""
    rows = textwrap.wrap(text, width=max(4, chars), break_long_words=True)
    if len(rows) > lines:
        rest = " ".join(rows[lines - 1:])
        rows = rows[:lines - 1] + [rest[:max(1, chars - 1)].rstrip() + _ELLIPSIS]
    return "\n".join(rows)


def _list(value: Any, count: int, fallback: List[Any]) -> List[Any]:
    items = [v for v in (value if isinstance(value, list) else [])]
    if not items:
        items = list(fallback)
    while len(items) < count:
        items.append(fallback[len(items) % len(fallback)])
    return items[:count]


def _entry(value: Any, key: str) -> Any:
    return value.get(key) if isinstance(value, dict) else None


