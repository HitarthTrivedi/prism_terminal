def compose(copy: Optional[Dict[str, Any]] = None, width: int = 1080, height: int = 1920,
            fps: int = 60, logo: Optional[Dict[str, Any]] = None,
            palette: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """The reference film's grammar with `copy` in its slots. Eleven beats
    on one continuity thread ("signal"):

    scattered tiles → a band with labelled cards → tiles stream into a
    column while chat / phone / mail icons converge on a hub → a dark
    sphere hangs over a tree of thin lines among bokeh → a blue light sweeps
    in and a conversation plays in bubbles → a knowledge tree with cards →
    the Knowledge Base card over a glowing graph → a great arc and a fact →
    the glowing orb → the mark, the name, the tagline and the call to action.

    `logo`: {"src": "asset:<name>", "w": px, "h": px} puts the client's own
    mark where the reference's wordmark stands; without it the brand name
    is set in type. `palette`: {"accent", "accent2"} colour the two orbs of
    the orb beat; the rest of the colour is the reference's, because the
    reference is the target (the customer's bubble keeps the genre's blue).

    Coordinates are authored in 1080x1920 and scaled to the frame.
    """
    words = normalise_copy(copy)
    brand, tagline, cta = words["brand"], words["tagline"], words["cta"]
    accent = str((palette or {}).get("accent") or "#1d4fd8")
    accent2 = str((palette or {}).get("accent2") or "#1b7a6a")
    captions = words["captions"]
    s = width / 1080.0

    def P(x, y):
        return [round(x * s, 1), round(y * s, 1)]

    def S(v):
        return round(v * s, 2)

    def text(node_id, content, x, y, size, weight=600, fill="#F5F7FF", mode="standard",
             enter=None, exit_=None, **extra):
        node = {"id": node_id, "type": "text", "content": content, "position": P(x, y),
                "font_size": S(size), "font_weight": weight, "fill": fill, "mode": mode,
                "layer": "foreground"}
        node.update(extra)
        anim = {}
        if enter:
            anim["enter"] = enter
        if exit_:
            anim["exit"] = exit_
        if anim:
            node["animation"] = anim
        return node

    def fade_in(at, dur=0.5, dy=18, easing="power2.out"):
        tweens = [{"channel": "opacity", "from": 0, "to": 1}]
        if dy:
            tweens.append({"channel": "y", "from": S(dy), "to": 0, "easing": easing})
        return {"time": at, "duration": dur, "tweens": tweens}

    def fade_out(at, dur=0.4, dy=-12):
        tweens = [{"channel": "opacity", "from": 1, "to": 0}]
        if dy:
            tweens.append({"channel": "y", "from": 0, "to": S(dy), "easing": "power2.in"})
        return {"time": at, "duration": dur, "tweens": tweens}

    def slide_in(at, dur=0.8, dx=700):
        return {"time": at, "duration": dur, "tweens": [
            {"channel": "opacity", "from": 0, "to": 1, "easing": "power2.out"},
            {"channel": "x", "from": S(dx), "to": 0, "easing": "power3.out"},
            {"channel": "blur", "from": 10, "to": 0, "easing": "power2.out"}]}

    def slide_out(at, dur=0.6, dx=-420, easing="power3.in"):
        return {"time": at, "duration": dur, "tweens": [
            {"channel": "opacity", "from": 1, "to": 0, "easing": "power2.in"},
            {"channel": "x", "from": 0, "to": S(dx), "easing": easing},
            {"channel": "blur", "from": 0, "to": 12}]}

    def glass_card(node_id, x, y, w, h, lines, size=22, title=None, enter_at=0.3,
                   exit_at=None, key=None, blur=0.0, radius=18, tint="#0d1119",
                   transmission=0.42):
        children = []
        if title:
            children.append(text(f"{node_id}_t", title, 0, -h * 0.28, size + 8, 700))
        children.append(text(f"{node_id}_b", lines, 0, (h * 0.12 if title else 0), size, 400,
                             fill="rgba(245,247,255,0.86)", line_height=1.3))
        node = {"id": node_id, "type": "glass_panel", "position": P(x, y), "width": S(w),
                "height": S(h), "radius": S(radius), "tint": tint, "transmission": transmission,
                "blur": 16, "border_light": 0.5, "inner_shadow": 0.3, "specular": 0.25,
                "contrast_guard": "dark", "layer": "midground", "children": children,
                "animation": {"enter": fade_in(enter_at, 0.6, 26)}}
        if exit_at is not None:
            node["animation"]["exit"] = fade_out(exit_at)
        if key:
            node["continuity_key"] = key
        if blur:
            node["animation"]["enter"]["tweens"].append({"channel": "blur", "from": blur, "to": blur})
        return node

    def sweeping_card(node_id, x, y, w, h, label, at, tint):
        # pops in (an enter's from-value shows from the first frame, so the
        # pop is a short block from 0) and sweeps up and out on the exit block
        node = glass_card(node_id, x, y, w, h, label, 24, enter_at=at, tint=tint, transmission=0.5)
        node["children"][-1]["font_weight"] = 700
        node["children"][-1]["fill"] = "#FFFFFF"
        node["animation"]["enter"] = {"time": at, "duration": 0.12, "tweens": [
            {"channel": "opacity", "from": 0, "to": 1, "easing": "power2.out"}]}
        node["animation"]["exit"] = {"time": at + 0.1, "duration": 0.75, "tweens": [
            {"channel": "y", "from": 0, "to": -S(760), "easing": "power1.in"}]}
        return node

    def rising_card(node_id, x, y, w, h, lines, title, at, climb, over, tint="#0d1119",
                    hold=0.0, easing="none", drift=0):
        node = glass_card(node_id, x, y, w, h, lines, 15, title=title, enter_at=at, tint=tint,
                          transmission=0.35)
        # the card pops in at the bottom and climbs; a fade would take the
        # whole climb to finish, so there is none. With `hold` it sits for
        # that long first, the climb riding on the exit block (which only
        # moves it — nothing hides it afterwards).
        climb = [{"channel": "y", "from": 0, "to": -S(climb), "easing": easing}]
        if drift:
            climb.append({"channel": "x", "from": 0, "to": S(drift), "easing": "power3.in"})
        node["animation"]["enter"] = {"time": at, "duration": 0.05, "tweens": [
            {"channel": "opacity", "from": 0, "to": 1}]}
        node["animation"]["exit"] = {"time": at + hold, "duration": over, "tweens": climb}
        return node

