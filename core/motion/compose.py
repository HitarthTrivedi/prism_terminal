def _png_uri(rows) -> str:
    """rows of (r, g, b) as a data: URI PNG — stdlib only."""
    import base64
    import struct
    import zlib
    h, w = len(rows), len(rows[0])
    raw = b"".join(b"\x00" + bytes(v for px in row for v in px) for row in rows)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    return "data:image/png;base64," + base64.b64encode(png).decode("ascii")


def _sky_field(table, gain: float = 1.0) -> str:
    """A full-frame sky from a band colour table: 12 x 39 cells over the
    1080x1920 frame (the band's rows interpolated, its edge rows held
    beyond it), stretched smooth by the browser, over a two-stop gradient
    of its own top and bottom so the fill still reads as a gradient."""
    band = [[tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) for c in row.split()] for row in table]
    rows = []
    for k in range(39):
        j = (1920 / 39 * (k + 0.5) - 77) / (1037 / 21) - 0.5
        j0 = max(0, min(20, int(j // 1))); j1 = max(0, min(20, j0 + 1)); f = max(0.0, min(1.0, j - j0))
        rows.append([tuple(max(0, min(255, round(gain * (band[j0][x][i] * (1 - f) + band[j1][x][i] * f))))
                           for i in range(3)) for x in range(12)])
    top = "#%02x%02x%02x" % rows[0][6]
    bottom = "#%02x%02x%02x" % rows[-1][6]
    return f'url("{_png_uri(rows)}") center / 100% 100% no-repeat, linear-gradient(180deg, {top}, {bottom})'


